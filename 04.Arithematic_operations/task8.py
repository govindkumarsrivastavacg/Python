n1, n2 = -10, -4

print("\nTask 8 Results:")
print(f"positive - positive: {p1} - {p2} =", p1 - p2)
print(f"positive - negative: {p1} - ({n2}) =", p1 - n2)
print(f"negative - positive: {n1} - {p2} =", n1 - p2)
print(f"negative - negative: {n1} - ({n2}) =", n1 - n2)