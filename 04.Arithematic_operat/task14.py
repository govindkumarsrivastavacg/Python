print("True + 5  =", True + 5)   
print("False + 5 =", False + 5)   
print("True * 10 =", True * 10)  
print("False * 10 =", False * 10) 
print("True - 5  =", True - 5)    
print("False - 5 =", False - 5)   
# Explanation: Python automatically treats True as integer 1 and False as integer 0 when used in arithmetic.