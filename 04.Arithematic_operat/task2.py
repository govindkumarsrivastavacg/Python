print("Addition:", res_add, "Type:", type(res_add))
print("Subtraction:", res_sub, "Type:", type(res_sub))
print("Multiplication:", res_mul, "Type:", type(res_mul))
print("Division:", res_div, "Type:", type(res_div))
print("Floor Division:", res_fdiv, "Type:", type(res_fdiv))
